#!/usr/bin/env python3
"""LINEAGE.md: add a session entry and keep only the 3 newest in the body.

    python3 scripts/lineage-rollover.py --add memory/.staging/N/LINEAGE-entry.md
        inserts the entry (must start with "## SESSION N — Name") at the top, then rolls over
    python3 scripts/lineage-rollover.py              # rollover only
    python3 scripts/lineage-rollover.py --dry-run    # shows what it would do
    python3 scripts/lineage-rollover.py --regen-index

Rules:
- Every entry is saved verbatim to memory/archive/sessions/NNN-name.md (the complete archive).
- LINEAGE.md keeps the THRESHOLD newest (newest on top), older ones drop out of the body.
- memory/archive/sessions/INDEX.md is generated from the archive, not edited by hand.
- The script is idempotent: running it a second time changes nothing.
- "## SESSION" headings inside code blocks (```) are ignored, and so is "## SESSION N — Name" with a letter
  instead of a number (the example in LINEAGE).

Standard library only, Python 3.8+.
"""
import argparse
import datetime
import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _fileutil import Lock, atomic_write  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
LINEAGE = ROOT / "memory" / "LINEAGE.md"
ARCHIVE = ROOT / "memory" / "archive" / "sessions"
LOCK = ROOT / "memory" / ".lineage.lock"
THRESHOLD = 3

HDR = re.compile(r"^## SESSION (\d+) — (.+?)\s*$")


def split(text):
    """(preamble, [(number, name, block)]) — block includes the heading, without the trailing separator."""
    lines = text.splitlines()
    heads = []
    in_fence = False
    for i, ln in enumerate(lines):
        if ln.lstrip().startswith("```"):
            in_fence = not in_fence
            continue
        if not in_fence:
            m = HDR.match(ln)
            if m:
                heads.append((i, int(m.group(1)), m.group(2).strip()))
    if not heads:
        return text.rstrip() + "\n", []
    pre = "\n".join(lines[:heads[0][0]]).rstrip() + "\n"
    blocks = []
    for k, (i, number, name) in enumerate(heads):
        end = heads[k + 1][0] if k + 1 < len(heads) else len(lines)
        b = lines[i:end]
        while b and (not b[-1].strip() or re.fullmatch(r"-{3,}", b[-1].strip())):
            b.pop()
        blocks.append((number, name, "\n".join(b)))
    return pre, blocks


def slug(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "session"


def entry_date(block):
    m = re.search(r"\*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})", block) or re.search(r"(\d{4}-\d{2}-\d{2})", block)
    return m.group(1) if m else ""


def topic(block):
    m = re.search(r"^### What was done\s*\n+\s*(?:[-*]\s*)?(.+)$", block, re.M)
    t = m.group(1).strip() if m else ""
    t = re.sub(r"[*`]", "", t).replace("|", "/")
    return (t[:137] + "...") if len(t) > 140 else t


def archive_text(number, name, block):
    return ("---\nname: Session %d — %s\ndescription: %s\ntype: archive\nstatus: archived\nsession: %d\ndate: %s\n---\n\n%s\n"
            % (number, name, topic(block) or "session record", number, entry_date(block), block))


def archive(blocks, dry):
    written = 0
    for number, name, block in blocks:
        target = ARCHIVE / ("%03d-%s.md" % (number, slug(name)))
        text = archive_text(number, name, block)
        # same number with a different name (a renamed session): I do not delete, only warn (deleting only into the Trash)
        for p in ARCHIVE.glob("%03d-*.md" % number):
            if p != target:
                print("WARNING: the archive also holds %s (same number, different name). Move the old file to the Trash: bash scripts/to-trash.sh %s"
                      % (p.name, p), file=sys.stderr)
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            written += 1
            if not dry:
                atomic_write(target, text)
    return written


def index(dry):
    rows = []
    for p in sorted(ARCHIVE.glob("[0-9]*.md")):
        t = p.read_text(encoding="utf-8")
        fm = re.match(r"^---\n(.*?)\n---", t, re.S)
        d = {}
        if fm:
            for ln in fm.group(1).splitlines():
                if ":" in ln:
                    k, v = ln.split(":", 1)
                    d[k.strip()] = v.strip()
        nm = re.sub(r"^Session \d+ — ", "", d.get("name", p.stem))
        rows.append("| [%s](%s) | %s | %s | %s |" % (d.get("session", p.name[:3]), p.name, nm, d.get("date", ""), d.get("description", "")))
    text = ("---\nname: LINEAGE Archive Index\ndescription: Index of all sessions (generated by scripts/lineage-rollover.py). Full texts in NNN-name.md.\n"
            "type: archive\nstatus: active\nlast_edited: %s\n---\n\n# Session archive\n\n"
            "> Generated by `scripts/lineage-rollover.py`, do not edit by hand.\n\n"
            "| # | Name | Date | Topic |\n| --- | --- | --- | --- |\n%s\n"
            % (datetime.date.today().isoformat(), "\n".join(rows)))
    target = ARCHIVE / "INDEX.md"
    # last_edited changes every day; I compare without it so the script stays idempotent
    def strip(t):
        return re.sub(r"last_edited: .*\n", "", t)
    if target.exists() and strip(target.read_text(encoding="utf-8")) == strip(text):
        return False
    if not dry:
        atomic_write(target, text)
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--add", metavar="FILE")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--regen-index", action="store_true")
    a = ap.parse_args()
    with Lock(LOCK):  # the whole read-modify-write (LINEAGE, archive, INDEX) is one critical section
        return run(a)


def run(a):
    if a.regen_index:
        print("INDEX regenerated." if index(a.dry_run) else "INDEX unchanged.")
        return 0
    if not LINEAGE.exists():
        print("LINEAGE.md is missing: %s" % LINEAGE, file=sys.stderr)
        return 1

    pre, blocks = split(LINEAGE.read_text(encoding="utf-8"))
    if a.add:
        new = Path(a.add).read_text(encoding="utf-8").strip()
        m = HDR.match(new.splitlines()[0]) if new else None
        if not m:
            print("The entry must start with the line '## SESSION N — Name' (N a number).", file=sys.stderr)
            return 2
        number, name = int(m.group(1)), m.group(2).strip()
        new = "\n".join(new.splitlines())
        blocks = [b for b in blocks if b[0] != number] + [(number, name, new.rstrip())]
        print("Entry for session %d inserted." % number)

    blocks.sort(key=lambda b: b[0], reverse=True)
    n_archived = archive(blocks, a.dry_run)
    kept = blocks[:THRESHOLD]
    dropped = [b[0] for b in blocks[THRESHOLD:]]
    body = pre.rstrip() + "\n\n" + "\n\n---\n\n".join(b[2] for b in kept) + "\n" if kept else pre
    changed = body != LINEAGE.read_text(encoding="utf-8")
    if changed and not a.dry_run:
        atomic_write(LINEAGE, body)
    i = index(a.dry_run)
    print("Rollover%s: LINEAGE keeps %d (%s), dropped from the body: %s, archive written %dx, INDEX %s."
          % (" (dry run)" if a.dry_run else "", len(kept), ", ".join(str(b[0]) for b in kept) or "none",
             ", ".join(map(str, dropped)) or "none", n_archived, "regenerated" if i else "unchanged"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
