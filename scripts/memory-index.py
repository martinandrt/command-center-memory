#!/usr/bin/env python3
"""Generate memory/MEMORY.md (the memory index) from the frontmatter of the files.

    python3 scripts/memory-index.py            # rewrites the section between AUTO:START and AUTO:END
    python3 scripts/memory-index.py --dry-run  # prints to stdout, changes nothing
    python3 scripts/memory-index.py --check    # exit 1 if the index differs from the disk

Reads `name` and `description` from the frontmatter (single-line "key: value") of every .md in memory/,
except BRAIN, LINEAGE, MEMORY, README_MEMORY and the folders archive/, .staging/, .index/.
A file without `description` still gets into the index, with a warning (on stderr): without a description it cannot be found.
MEMORY.md is not edited by hand; it is a listing, not instructions (the instructions are in README_MEMORY.md).

Standard library only, Python 3.8+.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _fileutil import Lock, atomic_write  # noqa: E402

MEM = Path(__file__).resolve().parent.parent / "memory"
MEMORY_MD = MEM / "MEMORY.md"
SKIP_FILES = {"MEMORY.md", "LINEAGE.md", "BRAIN.md", "README_MEMORY.md"}
SKIP_FOLDERS = {"archive", ".staging", ".index"}
START, END = "<!-- AUTO:START -->", "<!-- AUTO:END -->"

SECTIONS = [
    ("feedback", "Feedback (lessons from corrections)"),
    ("knowledge", "Knowledge (how things work)"),
    ("projects", "Projects (state of work in progress)"),
    ("reference", "Reference (stable facts to look up)"),
    ("_other", "Other"),
]

HEADER = """---
name: MEMORY
description: Auto-generated memory index (what is in memory/). Do not edit, generated by scripts/memory-index.py.
type: index
status: active
last_edited: {date}
---

# MEMORY — index

> A listing of files taken from the frontmatter. It answers "what is in memory", not "where to write it" (that is README_MEMORY.md).
> Generated by `python3 scripts/memory-index.py`, not edited by hand.

{start}
{end}
"""


def frontmatter(p):
    try:
        t = p.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return {}
    m = re.match(r"^---\n(.*?)\n---", t, re.S)
    if not m:
        return {}
    fm = {}
    for ln in m.group(1).splitlines():
        if ":" in ln and not ln.startswith((" ", "\t", "#")):
            k, v = ln.split(":", 1)
            fm[k.strip()] = v.strip().strip("\"'")
    return fm


def collect():
    sections = {k: [] for k, _ in SECTIONS}
    warnings = []
    for p in sorted(MEM.rglob("*.md")):
        rel = p.relative_to(MEM)
        if p.name in SKIP_FILES and len(rel.parts) == 1:
            continue
        if set(rel.parts[:-1]) & SKIP_FOLDERS:
            continue
        fm = frontmatter(p)
        if not fm.get("description"):
            warnings.append("%s: missing frontmatter or description" % rel)
        top = rel.parts[0] if len(rel.parts) > 1 else "_other"
        key = top if top in sections else "_other"
        sections[key].append("- [%s](%s) — %s" % (fm.get("name") or p.stem, rel.as_posix(), fm.get("description", "(no description)")))
    return sections, warnings


def render(sections):
    out = []
    for k, title in SECTIONS:
        out.append("### %s\n" % title)
        out.append("\n".join(sections[k]) if sections[k] else "_(nothing yet)_")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    # one lock for the whole collect-render-write pass: two windows cannot write an older index over a newer one
    with Lock(MEMORY_MD.parent / ".memory-index.lock"):
        return _main()


def _main():
    argv = sys.argv[1:]
    if {"-h", "--help"} & set(argv):
        print(__doc__)
        return 0
    sections, warnings = collect()
    for w in warnings:
        print("WARNING: " + w, file=sys.stderr)
    body = render(sections)
    if "--dry-run" in argv:
        print(body)
        return 0
    if MEMORY_MD.exists():
        original = MEMORY_MD.read_text(encoding="utf-8")
    else:
        import datetime
        original = HEADER.format(date=datetime.date.today().isoformat(), start=START, end=END)
    if START not in original or END not in original:
        print("MEMORY.md has no AUTO:START / AUTO:END markers.", file=sys.stderr)
        return 1
    before, rest = original.split(START, 1)
    _, after = rest.split(END, 1)
    new = "%s%s\n\n%s%s%s" % (before, START, body, END, after)
    if "--check" in argv:
        if new != original:
            print("MEMORY.md is out of date: run python3 scripts/memory-index.py")
            return 1
        print("MEMORY.md is up to date.")
        return 0
    if new != original or not MEMORY_MD.exists():
        atomic_write(MEMORY_MD, new)
        print("MEMORY.md regenerated (%d files)." % sum(len(v) for v in sections.values()))
    else:
        print("MEMORY.md unchanged.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
